// The agent2telegram gateway runs as a systemd --user service generated at install time.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

export const GATEWAY_SERVICE = "agent2telegram-gateway";
/** Earlier names of the same service (Claude-only gateway). */
export const LEGACY_GATEWAY_SERVICES = ["agent2telegram-claude", "claude-telegram-gateway"];

export function serviceDir(): string {
  return join(process.env.XDG_CONFIG_HOME || join(homedir(), ".config"), "systemd", "user");
}

export function gatewayUnit(options: { node: string; appDir: string; a2tHome: string }): string {
  return [
    "# Generated by agent2telegram (a2t). The one process that polls each agent's Bot",
    "# and serves every Pi, Claude Code and Codex session on this machine.",
    "[Unit]",
    "Description=agent2telegram gateway (Pi, Claude Code and Codex)",
    "",
    "[Service]",
    `ExecStart=${options.node} ${join(options.appDir, "dist", "lib", "gateway", "main.js")}`,
    `Environment=AGENT2TELEGRAM_DIR=${options.a2tHome}`,
    "Restart=always",
    "RestartSec=2",
    "",
    "[Install]",
    "WantedBy=default.target",
    "",
  ].join("\n");
}

export type Run = (command: string, args: string[]) => string;
export const run: Run = (command, args) => execFileSync(command, args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });

/** Write the unit, reload systemd, enable and (re)start it. Returns what changed. */
export function installGatewayService(unit: string, exec: Run = run): string[] {
  const done: string[] = [];
  mkdirSync(serviceDir(), { recursive: true });
  const path = join(serviceDir(), `${GATEWAY_SERVICE}.service`);
  const before = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (before !== unit) { writeFileSync(path, unit); done.push(`写入 ${path}`); }
  exec("systemctl", ["--user", "daemon-reload"]);
  exec("systemctl", ["--user", "enable", `${GATEWAY_SERVICE}.service`]);
  exec("systemctl", ["--user", "restart", `${GATEWAY_SERVICE}.service`]);
  done.push(`已启动 ${GATEWAY_SERVICE}`);
  return done;
}

export function removeGatewayService(name: string, exec: Run = run): boolean {
  const path = join(serviceDir(), `${name}.service`);
  try { exec("systemctl", ["--user", "disable", "--now", `${name}.service`]); } catch { /* not loaded */ }
  const existed = existsSync(path);
  rmSync(path, { force: true });
  try { exec("systemctl", ["--user", "daemon-reload"]); } catch { /* no user manager */ }
  return existed;
}

export function gatewayStatus(exec: Run = run): string {
  try { return exec("systemctl", ["--user", "is-active", `${GATEWAY_SERVICE}.service`]).trim(); } catch (error) {
    return String((error as { stdout?: string }).stdout ?? "unknown").trim() || "inactive";
  }
}

export function lingerEnabled(user: string, exec: Run = run): boolean {
  try { return exec("loginctl", ["show-user", user, "-p", "Linger", "--value"]).trim() === "yes"; } catch { return false; }
}
